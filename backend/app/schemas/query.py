from typing import Any, Literal

from pydantic import BaseModel, Field

MAX_QUESTION_CHARS = 500
MAX_HISTORY_TURNS = 4

Status = Literal["answered", "clarification", "unsupported", "rejected", "failed"]


class HistoryTurnIn(BaseModel):
    """One earlier exchange, sent back by the client for follow-up questions."""

    question: str = Field(max_length=MAX_QUESTION_CHARS)
    sql: str | None = Field(default=None, max_length=5000)
    reply: str | None = Field(default=None, max_length=1000)


class QueryRequest(BaseModel):
    question: str = Field(min_length=1, max_length=MAX_QUESTION_CHARS)
    # Older turns beyond MAX_HISTORY_TURNS are dropped by the server
    history: list[HistoryTurnIn] = Field(default_factory=list, max_length=20)


class SqlRequest(BaseModel):
    sql: str = Field(min_length=1, max_length=10_000)


class ResultColumn(BaseModel):
    name: str
    type: str


class ResultSetOut(BaseModel):
    columns: list[ResultColumn]
    # Rows are arrays in column order, so duplicate column names survive
    rows: list[list[Any]]
    row_count: int
    # True when the query matched more rows than row_limit
    truncated: bool
    row_limit: int


class Attempt(BaseModel):
    """A try that failed before the final answer."""

    stage: Literal["model_output", "validation", "execution"]
    sql: str | None
    error: str


class Timings(BaseModel):
    generation_ms: float = 0
    execution_ms: float = 0
    total_ms: float = 0


class QueryResponse(BaseModel):
    status: Status
    question: str
    # The clarification question, why a request is unsupported, or the error
    message: str | None = None
    # What the query computes. Written before the query ran, so it never
    # describes results.
    explanation: str = ""
    assumptions: list[str] = Field(default_factory=list)
    # Suggested rephrasings when status is "clarification"
    options: list[str] = Field(default_factory=list)
    # The model's SQL
    sql: str | None = None
    # What actually ran: sql re-generated by the guard, with the row cap
    executed_sql: str | None = None
    result: ResultSetOut | None = None
    attempts: list[Attempt] = Field(default_factory=list)
    model: str | None = None
    cached: bool = False
    timings: Timings = Field(default_factory=Timings)


class ErrorDetail(BaseModel):
    code: str
    message: str


class ErrorResponse(BaseModel):
    error: ErrorDetail
